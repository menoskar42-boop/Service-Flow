// shared/card-capacity.ts — سعة كارت الـ MSAN والفاضى فيه.
//
// السعة مش موجودة فى ملف البورتات، فبنستنتجها بقواعد السنترال:
//   • الأصل إن كل الكروت سعتها 64 بورت.
//   • كابينة 11-2-76-01 كروتها 32 (استثناء معروف).
//   • أى كارت عليه **أكتر من 68** خط شغّال ده كارت 128 — مفيش كارت 64 يشيل العدد ده.
// الفاضى = السعة − الشغّال، وبيتقفل عند الصفر: الكارت اللى عليه 65 أو 68 على كارت
// 64 معناه إنه مليان (الزيادة البسيطة دى بتيجى من صفوف مكرّرة/قديمة فى الملف) —
// من غير القفل ده كان هيطلع رقم سالب.
//
// ⚠️ مصدر واحد للقاعدة: بيستخدمه تقرير «الكروت (شيلف/سلوت)» وتقرير «الفاضى لكل
// نوع بورت» وشاشة «غيّر البورت» (عن طريق /api/phone-ports/cabinet-free) — عشان
// الأرقام تفضل متطابقة فى الثلاثة ومايحصلش drift لو القاعدة اتغيّرت.
// ============================================================================

/** كباين كروتها 32 بورت بدل 64 */
const CAB_32 = new Set(["11-2-76-01"]);

/** توحيد كود كابينة المسان للمقارنة (شيل المسافات) */
export const normMsanCode = (s: unknown): string => String(s ?? "").replace(/\s+/g, "").trim();

/** سعة الكارت بالبورتات — من كود الكابينة وعدد الشغّال على الكارت */
export function cardCapacityOf(msanCode: unknown, working: number): number {
  const w = working || 0;
  if (CAB_32.has(normMsanCode(msanCode)) && w <= 32) return 32;
  return w > 68 ? 128 : 64;
}

/** الفاضى فى الكارت (مايقلّش عن صفر) */
export function cardFreeOf(msanCode: unknown, working: number): number {
  return Math.max(0, cardCapacityOf(msanCode, working) - (working || 0));
}
