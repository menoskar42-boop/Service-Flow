/** يرجّع سبب الإغلاق المقابل للكود (يتعامل مع الأكواد النصية/العشرية مثل "13.0"). */
export function closeReason(code: string | number | null | undefined): string {
  if (code == null || code === "") return "";
  const raw = String(code).trim();
  // أكواد عشرية مثل "13.0" → "13"
  const norm = /^\d+(\.0+)?$/.test(raw) ? String(parseInt(raw, 10)) : raw;
  return CLOSE_CODE_REASONS[norm] ?? "";
}

/** كود + سبب فى نص واحد للعرض (مثال: "13 - البكس"). */
export function closeCodeWithReason(code: string | number | null | undefined): string {
  if (code == null || code === "") return "";
  const reason = closeReason(code);
  const c = String(code).trim();
  return reason ? `${c} - ${reason}` : c;
}
