import { useAuth } from "@/hooks/use-auth";
import { ROLES } from "@shared/schema";

// ── مين بيشوف أزرار القياس / رفع السرعة / إيقاف PO؟ ──────────────────────────
// القاعدة (مطلوبة صراحةً من المستخدم):
//   • **بحث برقم التليفون** → لكل المستخدمين. الصفحة دى بترسم أزرارها بنفسها من غير
//     الهوك ده أصلاً، فهى مالهاش دعوة بالتشديد اللى هنا.
//   • **زر القياس اللى جنب رقم الأكونت فى كل صف** (رقم واحد) → لكل المستخدمين برضه،
//     مقصود إنه مايتلفّش بالهوك ده.
//   • **أزرار الشريط العلوى فى التقارير** (اللى بتقيس/ترفع **مجموعة خطوط** دفعة واحدة)
//     → **السوبر أدمن بس**.
//
// السبب: أزرار الشريط بتبعت باتش لطابور التنفيذ (مئات وآلاف الأرقام) وبتحجز جهاز
// التنفيذ ساعات. كانت مفتوحة كمان للأدمن (ومنه مدير السنترال) والشئون الخارجية (ومنها
// مهندس الكوابل) — فمستخدم زى مسئول البيانات كان بيقدر يبعت باتش من تقرير زى «خطوط
// أسكورها أعلى من 100» ويقفل الطابور. ده حصل فعلاً وبقى الحد الحالى.
//
// alwaysShow متسابة كمخرج لو احتجنا نفتح شاشة معيّنة للكل من غير ما نلمس الباقى.
export function useSpeedToolsVisible(alwaysShow = false): boolean {
  const { user } = useAuth();
  return alwaysShow || user?.role === ROLES.SUPER_ADMIN;
}

// هل المستخدم سوبر أدمن؟ (يُستخدم مع dispatchSpeedTool: السوبر أدمن ينفّذ محلياً لو مفيش جهاز تنفيذ)
export function useIsSuperAdmin(): boolean {
  const { user } = useAuth();
  return user?.role === ROLES.SUPER_ADMIN;
}
